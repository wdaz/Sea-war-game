// Copies the woff2 files the interface actually uses out of the @fontsource
// packages and writes assets/fonts/fonts.css.
//
// The runtime must stay self-contained: no Google Fonts, no CDN. The woff2
// files are committed, so @fontsource is a devDependency needed only to
// regenerate them:  node scripts/build-fonts.mjs
//
// Saira Condensed, Inter and IBM Plex Mono are all SIL Open Font Licence 1.1.
//
// Saira Condensed replaces Rajdhani, which the design named but which has no
// glyph for U+018F/U+0259 (Ə/ə) and therefore cannot set Azerbaijani.

import { copyFile, mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, 'assets', 'fonts');

// Only the weights main.css actually asks for.
const FAMILIES = [
  { pkg: 'saira-condensed', family: 'Saira Condensed', weights: [700] },
  { pkg: 'inter', family: 'Inter', weights: [400, 500, 700] },
  { pkg: 'ibm-plex-mono', family: 'IBM Plex Mono', weights: [400, 600, 700] },
];

// Azerbaijani needs both: ç ö ü live in latin, while ə ğ ı İ ş sit in
// latin-ext (U+0100-02BA).
const SUBSETS = ['latin', 'latin-ext'];

// Only the combined per-weight sheet carries unicode-range; the per-subset
// sheets omit it. Locate the @font-face block whose src names this subset.
async function unicodeRange(pkg, subset, weight) {
  const sheet = join(ROOT, 'node_modules', '@fontsource', pkg, `${weight}.css`);
  const css = await readFile(sheet, 'utf8');

  for (const block of css.split('@font-face')) {
    if (!block.includes(`${pkg}-${subset}-${weight}-normal.woff2`)) continue;
    const match = block.match(/unicode-range:\s*([^;]+);/);
    if (match) return match[1].trim();
  }
  throw new Error(`No unicode-range for ${pkg}/${subset}/${weight}`);
}

await rm(OUT_DIR, { recursive: true, force: true });
await mkdir(OUT_DIR, { recursive: true });

const blocks = [];
let copied = 0;

for (const { pkg, family, weights } of FAMILIES) {
  for (const subset of SUBSETS) {
    for (const weight of weights) {
      const range = await unicodeRange(pkg, subset, weight);
      const name = `${pkg}-${subset}-${weight}-normal.woff2`;
      await copyFile(
        join(ROOT, 'node_modules', '@fontsource', pkg, 'files', name),
        join(OUT_DIR, name),
      );
      copied++;
      blocks.push(`@font-face {
  font-family: '${family}';
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: url('${name}') format('woff2');
  unicode-range: ${range};
}`);
    }
  }
}

const header = `/* Generated by scripts/build-fonts.mjs. Do not edit by hand.
 *
 * Saira Condensed, Inter and IBM Plex Mono, SIL Open Font Licence 1.1.
 * Served locally so the interface makes no third-party requests.
 */`;

await writeFile(join(OUT_DIR, 'fonts.css'), `${header}\n\n${blocks.join('\n\n')}\n`);
console.log(`fonts.css written, ${copied} woff2 files copied to assets/fonts/`);
