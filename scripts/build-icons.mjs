// Regenerates the GLYPHS table in src/ui/icons.js from lucide-static.
//
// The runtime must stay self-contained, so the paths are vendored into
// src/ui/icons.js rather than imported. Run this only when the icon set
// changes:  node scripts/build-icons.mjs
//
// Lucide is ISC licensed. https://lucide.dev

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ICON_DIR = join(ROOT, 'node_modules', 'lucide-static', 'icons');
const TARGET = join(ROOT, 'src', 'ui', 'icons.js');

const NAMES = [
  'radar', 'radio-tower', 'crosshair', 'target',
  'circle', 'circle-dot', 'skull', 'triangle-alert',
  'lock', 'shield', 'shield-check', 'ship',
  'refresh-cw', 'rotate-cw', 'wand-sparkles', 'trophy',
];

function innerMarkup(name) {
  const raw = readFileSync(join(ICON_DIR, `${name}.svg`), 'utf8');
  const open = raw.indexOf('>', raw.indexOf('<svg'));
  const close = raw.lastIndexOf('</svg>');
  if (open === -1 || close === -1) throw new Error(`Cannot parse ${name}.svg`);

  return raw.slice(open + 1, close)
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s*\/>/g, '/>')
    .replace(/\s+/g, ' ')
    .trim();
}

const version = JSON.parse(
  readFileSync(join(ROOT, 'node_modules', 'lucide-static', 'package.json'), 'utf8'),
).version;

const body = NAMES
  .map((name) => `  '${name}': '${innerMarkup(name).replace(/'/g, "\\'")}',`)
  .join('\n');

const block = `// Generated by scripts/build-icons.mjs from lucide-static v${version} (ISC).
// Do not edit by hand; run \`node scripts/build-icons.mjs\` instead.
const GLYPHS = {
${body}
};`;

const source = readFileSync(TARGET, 'utf8');
const start = source.indexOf('const GLYPHS = {');
const end = source.indexOf('};', start);
if (start === -1 || end === -1) throw new Error('GLYPHS block not found in icons.js');

const prefixStart = source.lastIndexOf('// Generated by', 0) === -1
  ? source.lastIndexOf('\n', source.lastIndexOf('//', start)) + 1
  : start;

const before = source.slice(0, start);
const after = source.slice(end + 2);

// Drop any comment lines immediately preceding the old GLYPHS block.
const cleanedBefore = before.replace(/(?:^\/\/.*\n)+$/m, '');

writeFileSync(TARGET, `${cleanedBefore}${block}${after}`);
console.log(`icons.js updated from lucide-static v${version} (${NAMES.length} glyphs)`);
